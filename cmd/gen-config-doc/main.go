package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	"github.com/Suvukaraz/leanterm/internal/config"
	toml "github.com/pelletier/go-toml/v2"
)

func main() {
	cfg := config.Default()

	data, err := toml.Marshal(cfg)
	if err != nil {
		fmt.Fprintf(os.Stderr, "failed to marshal default config: %v\n", err)
		os.Exit(1)
	}

	var buf bytes.Buffer
	buf.WriteString("# LeanTerm Configuration Reference\n\n")
	buf.WriteString("> This file is automatically generated from `internal/config/schema.go` and `defaults.go`.\n")
	buf.WriteString("> Do not edit manually.\n\n")
	buf.WriteString("## Default `config.toml`\n\n")
	buf.WriteString("```toml\n")
	buf.Write(data)
	buf.WriteString("```\n")

	outPath := "docs/config-reference.md"
	if len(os.Args) > 1 {
		outPath = os.Args[1]
	}

	if err := os.MkdirAll(filepath.Dir(outPath), 0755); err != nil {
		fmt.Fprintf(os.Stderr, "failed to create dir: %v\n", err)
		os.Exit(1)
	}

	if err := os.WriteFile(outPath, buf.Bytes(), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "failed to write doc: %v\n", err)
		os.Exit(1)
	}

	fmt.Printf("Generated %s successfully.\n", outPath)
}
